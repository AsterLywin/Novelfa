package com.novelfa.reader.data

import androidx.room.Database
import androidx.room.RoomDatabase
import androidx.room.migration.Migration
import androidx.sqlite.db.SupportSQLiteDatabase

@Database(entities = [BookEntity::class], version = 4, exportSchema = true)
abstract class ReaderDb : RoomDatabase() {
    abstract fun bookDao(): BookDao
}

/**
 * 1 → 2: adds the nullable `originalFileName` column (used to disambiguate
 * duplicate/generic book titles). Nullable with no default, so existing rows
 * migrate untouched.
 */
val MIGRATION_1_2: Migration = object : Migration(1, 2) {
    override fun migrate(db: SupportSQLiteDatabase) {
        db.execSQL("ALTER TABLE books ADD COLUMN originalFileName TEXT")
    }
}

/**
 * 2 → 3: adds the nullable `lastAnchor` column (paged-mode text-point
 * anchor within `lastChapterIndex`). Nullable, so existing rows migrate
 * untouched and simply reopen at their chapter start until a paged
 * turn saves an anchor. NOTE: the exported schema file for version 3
 * (android/app/schemas/.../3.json) is generated by the next build
 * (exportSchema = true) and should be committed then; it is not
 * hand-written here because its identityHash is computed by Room.
 */
val MIGRATION_2_3: Migration = object : Migration(2, 3) {
    override fun migrate(db: SupportSQLiteDatabase) {
        db.execSQL("ALTER TABLE books ADD COLUMN lastAnchor TEXT")
    }
}

/**
 * 3 → 4: adds the in-place import columns. `sourceUri` is nullable
 * (copy-imported books have none); `importMode` defaults to "COPY"
 * so every existing row keeps exactly the behaviour it had — the
 * in-place mode only ever applies to books imported after the user
 * flips the Settings switch.
 */
val MIGRATION_3_4: Migration = object : Migration(3, 4) {
    override fun migrate(db: SupportSQLiteDatabase) {
        db.execSQL("ALTER TABLE books ADD COLUMN sourceUri TEXT")
        db.execSQL("ALTER TABLE books ADD COLUMN importMode TEXT NOT NULL DEFAULT 'COPY'")
    }
}
